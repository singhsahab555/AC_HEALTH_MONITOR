import pandas as pd
from sqlalchemy import create_engine, text , MetaData
from sqlalchemy.dialects.postgresql import insert

import os
from pathlib import Path
from urllib.parse import quote_plus

import yaml

# ── Credentials: connection details from config/config.yaml, password from the
#    AC_PG_PASSWORD environment variable (never hard-code it here). ───────────
_CFG_PATH = Path(__file__).resolve().parent.parent / "config" / "config.yaml"
with open(_CFG_PATH, encoding="utf-8") as _f:
    _DB = yaml.safe_load(_f)["database"]

PG_CONFIG = {
    "host":     _DB["host"],
    "port":     _DB["port"],
    "dbname":   _DB["dbname"],
    "user":     _DB["user"],
    "password": os.environ.get("AC_PG_PASSWORD") or _DB.get("password") or "",
}

encoded_password = quote_plus(PG_CONFIG["password"])

CONN_STR = (
    f"postgresql+psycopg2://{PG_CONFIG['user']}:{encoded_password}"
    f"@{PG_CONFIG['host']}:{PG_CONFIG['port']}/{PG_CONFIG['dbname']}"
)

DDL = """
-- Core anomaly results (one row per cycle)
CREATE TABLE IF NOT EXISTS ac_anomaly_results (
    id                          SERIAL PRIMARY KEY,
    ac_id                       VARCHAR(32)   NOT NULL,
    cycle_number                INTEGER,
    cycle_start                 TIMESTAMPTZ,
    cycle_end                   TIMESTAMPTZ,
    runtime_minutes             FLOAT,
    duty_cycle_pct              FLOAT,
    delta_t_mean                FLOAT,
    current_mean_a              FLOAT,
    current_peak_a              FLOAT,
    compressor_load_mean_kw     FLOAT,
    fan_load_mean_kw            FLOAT,
    total_load_mean_kw          FLOAT,
    cop_proxy                   FLOAT,
    efficiency_ratio            FLOAT,
    load_stress_index           FLOAT,
    energy_consumed_kwh         FLOAT,
    overall_score               FLOAT,
    anomaly_level               VARCHAR(16),
    if_anomaly                  SMALLINT DEFAULT 0,
    if_score                    FLOAT,
    xgb_anomaly_level           VARCHAR(16),
    xgb_prob_critical           FLOAT,
    anomaly_type                TEXT,
    anomaly_count               INTEGER,
    short_cycle_flag            SMALLINT DEFAULT 0,
    poor_cooling_flag           SMALLINT DEFAULT 0,
    high_stress_flag            SMALLINT DEFAULT 0,
    created_at                  TIMESTAMPTZ DEFAULT NOW()
);

-- Indexes for dashboard queries
CREATE INDEX IF NOT EXISTS idx_ac_anomaly_ac_id
    ON ac_anomaly_results(ac_id);
CREATE INDEX IF NOT EXISTS idx_ac_anomaly_cycle_start
    ON ac_anomaly_results(cycle_start DESC);
CREATE INDEX IF NOT EXISTS idx_ac_anomaly_level
    ON ac_anomaly_results(anomaly_level);

-- Forecast table
CREATE TABLE IF NOT EXISTS ac_forecasts (
    id          SERIAL PRIMARY KEY,
    ac_id       VARCHAR(32)  NOT NULL,
    metric      VARCHAR(64),
    ds          TIMESTAMPTZ,
    yhat        FLOAT,
    yhat_lower  FLOAT,
    yhat_upper  FLOAT,
    predicted_anomaly SMALLINT DEFAULT 0,
    created_at  TIMESTAMPTZ DEFAULT NOW()
);

-- Health report (per AC per run)
CREATE TABLE IF NOT EXISTS ac_health_report (
    id                  SERIAL PRIMARY KEY,
    ac_id               VARCHAR(32) NOT NULL,
    report_timestamp    TIMESTAMPTZ DEFAULT NOW(),
    total_cycles        INTEGER,
    if_anomalies        INTEGER,
    anomaly_rate_pct    FLOAT,
    overall_status      VARCHAR(16),
    top_anomaly_type    TEXT,
    avg_delta_t         FLOAT,
    avg_duty_cycle      FLOAT,
    avg_cop_proxy       FLOAT,
    avg_overall_score   FLOAT
);

-- Alarm log (generated by trigger or pipeline)
CREATE TABLE IF NOT EXISTS ac_alarms (
    id              SERIAL PRIMARY KEY,
    ac_id           VARCHAR(32) NOT NULL,
    alarm_time      TIMESTAMPTZ DEFAULT NOW(),
    severity        VARCHAR(16),   -- WARNING / CRITICAL
    anomaly_type    TEXT,
    metric          VARCHAR(64),
    metric_value    FLOAT,
    threshold       FLOAT,
    acknowledged    BOOLEAN DEFAULT FALSE,
    ack_by          VARCHAR(64),
    ack_at          TIMESTAMPTZ
);
"""


def create_schema(conn_str: str = CONN_STR) -> None:
    engine = create_engine(conn_str)
    with engine.connect() as conn:
        conn.execute(text(DDL))
        conn.commit()
    print("✅ Schema created.")


def write_results(df: pd.DataFrame, conn_str: str = CONN_STR,
                  if_exists: str = "append") -> None:
    """Upsert anomaly results into PostgreSQL."""
    engine = create_engine(conn_str)

    # Keep only columns that map to the table
    cols = [
        "ac_id", "cycle_number", "cycle_start", "cycle_end",
        "runtime_minutes", "duty_cycle_pct", "delta_t_mean",
        "current_mean_a", "current_peak_a",
        "compressor_load_mean_kw", "fan_load_mean_kw", "total_load_mean_kw",
        "cop_proxy", "efficiency_ratio", "load_stress_index",
        "energy_consumed_kwh", "overall_score", "anomaly_level",
        "if_anomaly", "if_score", "xgb_anomaly_level", "xgb_prob_critical",
        "anomaly_type", "anomaly_count",
        "short_cycle_flag", "poor_cooling_flag", "high_stress_flag",
    ]
    available = [c for c in cols if c in df.columns]
    df[available].to_sql(
        "ac_anomaly_results", engine,
        if_exists=if_exists, index=False, chunksize=500, method="multi",
    )
    print(f"✅ Written {len(df)} rows to ac_anomaly_results")


def write_forecasts(fc: pd.DataFrame, conn_str: str = CONN_STR) -> None:
    if fc.empty:
        return
    engine = create_engine(conn_str)
    fc.to_sql("ac_forecasts", engine, if_exists="append", index=False, chunksize=500)
    print(f"✅ Written {len(fc)} forecast rows")


def write_report(report: pd.DataFrame, conn_str: str = CONN_STR) -> None:
    if report.empty:
        return
        
    # 1. INJECT TIMESTAMP
    # pipeline.py doesn't generate this column, so we add it here 
    # to track the exact timeframe of this latest batch.
    if 'report_timestamp' not in report.columns:
        report['report_timestamp'] = pd.Timestamp.now()
        
    engine = create_engine(conn_str)
    metadata = MetaData()
    metadata.reflect(bind=engine)
    table = metadata.tables['ac_health_report']
    
    # Convert incoming AI batch into dictionaries
    records = report.to_dict(orient='records')
    
    with engine.begin() as conn:
        for record in records:
            # Build the base insert statement
            stmt = insert(table).values(record)
            
            # MERGE & AGGREGATE LOGIC ON CONFLICT
            upsert_stmt = stmt.on_conflict_do_update(
                index_elements=['ac_id'],  # Looks for the unique AC ID
                set_={
                    # ---------------------------------------------------
                    # 1. OVERWRITE: Replace all old aggregates with the latest timeframe
                    # ---------------------------------------------------
                    'report_timestamp': stmt.excluded.report_timestamp,
                    'overall_status': stmt.excluded.overall_status,
                    'avg_overall_score': stmt.excluded.avg_overall_score,
                    'anomaly_rate_pct': stmt.excluded.anomaly_rate_pct,
                    
                    # Added the missing columns from pipeline.py!
                    'if_anomalies': stmt.excluded.if_anomalies,
                    'top_anomaly_type': stmt.excluded.top_anomaly_type,
                    'avg_delta_t': stmt.excluded.avg_delta_t,
                    'avg_duty_cycle': stmt.excluded.avg_duty_cycle,
                    'avg_cop_proxy': stmt.excluded.avg_cop_proxy,
                    
                    # ---------------------------------------------------
                    # NO MORE ADDITION: We just overwrite with the new incoming total
                    # ---------------------------------------------------
                    'total_cycles': stmt.excluded.total_cycles
                }
            )
            conn.execute(upsert_stmt)
            
    print(f"✅ Fleet metrics merged and aggregated successfully for {len(report)} ACs.")


def insert_alarm(ac_id: str, severity: str, anomaly_type: str,
                 metric: str, value: float, threshold: float,
                 conn_str: str = CONN_STR) -> None:
    """Insert a real-time alarm row (call from monitoring loop)."""
    engine = create_engine(conn_str)
    sql = text("""
        INSERT INTO ac_alarms (ac_id, severity, anomaly_type, metric, metric_value, threshold)
        VALUES (:ac_id, :severity, :anomaly_type, :metric, :value, :threshold)
    """)
    with engine.connect() as conn:
        conn.execute(sql, {
            "ac_id": ac_id, "severity": severity,
            "anomaly_type": anomaly_type, "metric": metric,
            "value": value, "threshold": threshold,
        })
        conn.commit()


# ── REAL-TIME MONITORING LOOP (example) ──────────────────────────────────────
def monitor_loop(pipeline_fn, interval_seconds: int = 300) -> None:
    """
    Continuously re-run the pipeline and push alarms.
    Suitable for a cron job or systemd service.

    Example usage:
        from db import monitor_loop
        from pipeline import run_pipeline
        monitor_loop(run_pipeline, interval_seconds=300)
    """
    import time
    from pipeline import THRESHOLDS

    print(f"🔄 Monitor loop started (interval={interval_seconds}s)")
    while True:
        try:
            results  = pipeline_fn()
            df       = results["health_df"]
            forecasts = results["forecasts"]
            report   = results["report"]

            write_results(df, conn_str=CONN_STR)
            write_forecasts(forecasts, conn_str=CONN_STR)
            write_report(report, conn_str=CONN_STR)

            # Fire alarms for critical cycles detected this run
            critical = df[df["anomaly_level"] == "CRITICAL"]
            for _, row in critical.iterrows():
                insert_alarm(
                    ac_id=row["ac_id"],
                    severity="CRITICAL",
                    anomaly_type=row.get("anomaly_type", "Unknown"),
                    metric="delta_t_mean",
                    value=row.get("delta_t_mean", 0),
                    threshold=THRESHOLDS["delta_t_critical"],
                )
            print(f"✅ Cycle done. {len(critical)} critical alarm(s) fired.")
        except Exception as e:
            print(f"❌ Pipeline error: {e}")
        time.sleep(interval_seconds)


if __name__ == "__main__":
    # Run once to create schema
    create_schema()
